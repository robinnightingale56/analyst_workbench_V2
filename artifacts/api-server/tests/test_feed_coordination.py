def _engine(path: str):
    return create_engine(
        f"sqlite:///{path}",
        connect_args={"check_same_thread": False, "timeout": 10},
    )


def _event(provider: str, when: datetime | None = None) -> dict:
    when = when or datetime.now(timezone.utc) - timedelta(minutes=5)
    timestamp = when.isoformat().replace("+00:00", "Z")
    return {
        "id": provider,
        "title": f"{provider} report",
        "question": "What changed?",
        "url": f"https://news.example/{provider.lower().replace(' ', '-')}",
        "provider": provider,
        "publishedAt": timestamp,
        "retrievedAt": timestamp,
        "freshness": "CURRENT",
    }


def _spawn_cache_worker(database_path, start, calls, results):
    """Run a genuinely independent cache and connection pool."""
    from api_server import sources as child_sources
    from api_server.feed_coordination import PublicFeedCoordinator as ChildCoordinator

    async def fake_fetch(client, provider, url):
        calls.put(provider)
        # Keep the lease holder alive long enough for the peer to observe it.
        await asyncio.sleep(0.12)
        event = _event(provider)
        return [event], {
            "provider": provider,
            "status": "OK",
            "message": "Provider check succeeded.",
        }

    child_sources._fetch_current_provider = fake_fetch
    database = _engine(database_path)
    cache = child_sources.CurrentEventDiscoveryCache(
        ChildCoordinator(database, lease_seconds=1),
    )
    start.wait(10)
    try:
        results.put(("ok", asyncio.run(cache.get())))
    except BaseException as exc:
        results.put(("error", repr(exc)))
    finally:
        database.dispose()


def _spawn_abandoned_holder(database_path, marker_path, key, lease_seconds):
    """Acquire a lease, prove acquisition durably, then die without cleanup."""
    coordinator = PublicFeedCoordinator(
        _engine(database_path), lease_seconds=lease_seconds,
    )
    token, _, _, _ = coordinator.claim_or_read(key)
    Path(marker_path).write_text(token or "", encoding="utf-8")
    os._exit(23)


